#!/usr/bin/env python3
"""Real micro-benchmark for the TablePilot analysis core.

Times the three pipeline stages (profile → clean-preview → markdown report)
on the bundled demo table, plus profile on a synthetic ~10,000-row extension
of the same pattern (generated by sampling, never claimed as real user data).

Prints `METRIC name=value` lines so CI can capture and record them. No network,
no server, no I/O beyond reading demo/quality_issues_demo.csv once — the
numbers reflect the pure analysis cost in-process, so they are reproducible.

Usage (from repo root):
    python scripts/bench.py
    ROWS=50000 python scripts/bench.py       # override synthetic size
"""

from __future__ import annotations

import os
import statistics
import sys
import time
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO / "analysis_service"))

from app.analysis import (  # noqa: E402
    build_cleaning_preview,
    build_markdown_report,
    load_table_with_metadata,
    profile_table,
)

DEMO = REPO / "demo" / "quality_issues_demo.csv"
SYNTH_ROWS = int(os.environ.get("ROWS", "10000"))


def median_ms(fn, runs: int) -> float:
    """Return median wall-clock ms over `runs` invocations of fn()."""
    samples: list[float] = []
    for _ in range(runs):
        t0 = time.perf_counter()
        fn()
        samples.append((time.perf_counter() - t0) * 1000.0)
    return statistics.median(samples)


def make_synthetic_frame(base_rows: int, target_rows: int):
    """Build an honest synthetic frame by re-sampling the real demo rows."""
    import pandas as pd

    df = pd.read_csv(DEMO)
    reps = max(1, target_rows // max(base_rows, 1))
    big = pd.concat([df] * reps, ignore_index=True)
    big = big.sample(n=min(target_rows, len(big)), random_state=42).reset_index(drop=True)
    return big


def main() -> int:
    loaded = load_table_with_metadata(DEMO)
    frame, source = loaded["frame"], loaded["source"]
    base_rows = int(frame.shape[0])

    # Warm import caches once.
    profile = profile_table(DEMO.name, ".csv", frame.copy(), source.copy())
    _ = build_cleaning_preview(frame.copy(), DEMO.name)
    _ = build_markdown_report(profile)

    runs = 5
    profile_ms = median_ms(
        lambda: profile_table(DEMO.name, ".csv", frame.copy(), source.copy()), runs
    )
    clean_ms = median_ms(
        lambda: build_cleaning_preview(frame.copy(), DEMO.name), runs
    )
    report_ms = median_ms(
        lambda: build_markdown_report(
            profile_table(DEMO.name, ".csv", frame.copy(), source.copy())
        ),
        runs,
    )

    synth = make_synthetic_frame(base_rows, SYNTH_ROWS)
    synth_profile_ms = median_ms(
        lambda: profile_table("synthetic.csv", ".csv", synth.copy(), source.copy()),
        3,
    )

    print(f"METRIC demo_rows={base_rows}")
    print(f"METRIC synth_rows={int(synth.shape[0])}")
    print(f"METRIC profile_demo_ms={profile_ms:.2f}")
    print(f"METRIC clean_preview_demo_ms={clean_ms:.2f}")
    print(f"METRIC markdown_report_demo_ms={report_ms:.2f}")
    print(f"METRIC profile_synth_ms={synth_profile_ms:.2f}")
    print(
        f"benchmark: {base_rows}-row demo -> profile {profile_ms:.2f}ms, "
        f"clean-preview {clean_ms:.2f}ms, markdown {report_ms:.2f}ms; "
        f"{synth.shape[0]}-row synthetic -> profile {synth_profile_ms:.2f}ms"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
